#!/usr/bin/env bash
# Builds an unsigned Release .ipa from the prebuilt ios/ folder (macOS only).
# AltStore / SideStore re-sign it with your Apple ID when you install it.
# Run after: npx expo prebuild --platform ios
set -euo pipefail

cd ios
workspace=$(ls -d ./*.xcworkspace | head -n 1)
scheme=$(basename "$workspace" .xcworkspace)

xcodebuild -quiet \
  -workspace "$workspace" \
  -scheme "$scheme" \
  -configuration Release \
  -sdk iphoneos \
  -destination 'generic/platform=iOS' \
  -derivedDataPath build \
  CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY=""

# The Apple Watch app (watch/), for watchOS 8 and up, Series 3 included. Its
# Xcode project is generated by XcodeGen (brew install xcodegen); without it
# the .ipa is built without the watch app.
watch_app=build/watch/Release-watchos/LockScreenWatch.app
if command -v xcodegen >/dev/null; then
  (cd ../watch && xcodegen generate --quiet)
  xcodebuild -quiet \
    -project ../watch/LockScreenWatch.xcodeproj \
    -target LockScreenWatch \
    -configuration Release \
    -sdk watchos \
    SYMROOT="$PWD/build/watch" \
    CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO CODE_SIGN_IDENTITY=""
  lipo -info "$watch_app/LockScreenWatch"
else
  echo "warning: xcodegen not found; building without the Apple Watch app" >&2
fi

rm -rf build/Payload
mkdir build/Payload
cp -R build/Build/Products/Release-iphoneos/*.app build/Payload/
if [ -d "$watch_app" ]; then
  # iOS installs a companion watch app from the iPhone app's Watch folder.
  phone_app=$(ls -d build/Payload/*.app | head -n 1)
  mkdir -p "$phone_app/Watch"
  cp -R "$watch_app" "$phone_app/Watch/"
fi
(cd build && zip -qry LockScreen-unsigned.ipa Payload)
echo "Built ios/build/LockScreen-unsigned.ipa"
